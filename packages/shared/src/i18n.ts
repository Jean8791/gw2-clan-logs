export type Lang = "pt" | "en";
export type Dict = Record<string, string>;

/** O idioma inicial é sempre o português: só o valor exato "en" (escolhido no botão) muda isso. */
export const parseLang = (raw: string | null | undefined): Lang => (raw === "en" ? "en" : "pt");

/**
 * Texto de uma chave no idioma. Sem tradução cai no português e, por último, na própria chave (nunca vazio nem erro).
 * `{n}` e outros marcadores são trocados pelos valores. Com `n`, escolhe `chave_one` (n = 1) ou `chave_other`.
 */
export function translate(dicts: Record<Lang, Dict>, lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const plural = vars && typeof vars.n === "number" ? `${key}_${vars.n === 1 ? "one" : "other"}` : null;
  const pick = (l: Lang) => (plural && dicts[l][plural]) || dicts[l][key];
  const text = pick(lang) ?? pick("pt") ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m)) : text;
}

