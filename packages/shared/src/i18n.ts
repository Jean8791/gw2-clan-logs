const SCOPE_HINT_EN = { Group: "Volume generated for your group (includes you)", Self: "Volume generated only for you" };

/** Os boons "Out" (squad) ganham as versões Group e Self, com o mesmo nome e a dica do alcance. */
const scopedEn = (): Record<ScopedKey, StatEn> =>
  Object.fromEntries(
    (["Group", "Self"] as const).flatMap((suffix) =>
      BOON_BASES.map((b) => [`${b}${suffix}`, { ...BASE_EN[`${b}Out`], hint: SCOPE_HINT_EN[suffix] }]),
    ),
  ) as Record<ScopedKey, StatEn>;

export const STAT_EN: Record<StatKey, StatEn> = { ...BASE_EN, ...scopedEn() };

/** Nome, abreviação e dica de uma métrica no idioma (português = o que está em STAT_META). */
export function statText(key: StatKey, lang: Lang): { label: string; short: string; hint?: string } {
  if (lang === "en") return STAT_EN[key];
  const m = STAT_META[key];
  return { label: m.label, short: m.short, hint: m.hint };
}
